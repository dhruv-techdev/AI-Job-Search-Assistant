import { type MarketAnalysis } from "../shared/types.js";
import { saveFile, PATHS } from "../shared/tools.js";
import { logger } from "../shared/logger.js";
import path from "path";

/**
 * Generates a human-readable Markdown market analysis report.
 */
export function generateMarketReport(analysis: MarketAnalysis): void {
  const reportPath = path.join(PATHS.reports, "market-analysis.md");

  let md = `# Market Analysis Report\n\n`;
  md += `**Generated:** ${new Date(analysis.generatedAt).toLocaleString()}\n`;
  md += `**Postings Analyzed:** ${analysis.totalPostingsAnalyzed}\n\n`;
  md += `---\n\n`;

  // Top Required Skills
  md += `## Top Required Skills\n\n`;
  md += `| # | Skill | Count | % of Postings |\n`;
  md += `|---|-------|-------|---------------|\n`;
  for (let i = 0; i < analysis.topRequiredSkills.length; i++) {
    const s = analysis.topRequiredSkills[i];
    md += `| ${i + 1} | ${s.skill} | ${s.count} | ${s.percentage}% |\n`;
  }
  md += `\n`;

  // Top Preferred Skills
  if (analysis.topPreferredSkills.length > 0) {
    md += `## Top Preferred Skills\n\n`;
    md += `| # | Skill | Count | % of Postings |\n`;
    md += `|---|-------|-------|---------------|\n`;
    for (let i = 0; i < analysis.topPreferredSkills.length; i++) {
      const s = analysis.topPreferredSkills[i];
      md += `| ${i + 1} | ${s.skill} | ${s.count} | ${s.percentage}% |\n`;
    }
    md += `\n`;
  }

  // Experience Levels
  md += `## Experience Level Distribution\n\n`;
  const total = analysis.experienceLevels.entry + analysis.experienceLevels.mid + analysis.experienceLevels.senior;
  if (total > 0) {
    md += `| Level | Count | Percentage |\n`;
    md += `|-------|-------|------------|\n`;
    md += `| Entry-Level | ${analysis.experienceLevels.entry} | ${Math.round((analysis.experienceLevels.entry / total) * 100)}% |\n`;
    md += `| Mid-Level | ${analysis.experienceLevels.mid} | ${Math.round((analysis.experienceLevels.mid / total) * 100)}% |\n`;
    md += `| Senior-Level | ${analysis.experienceLevels.senior} | ${Math.round((analysis.experienceLevels.senior / total) * 100)}% |\n`;
  } else {
    md += `No experience level data available.\n`;
  }
  md += `\n`;

  // Salary Range
  md += `## Salary Overview\n\n`;
  if (analysis.salaryRange) {
    const { min, max, currency } = analysis.salaryRange;
    md += `- **Range:** ${currency || ""} ${min?.toLocaleString() || "N/A"} — ${max?.toLocaleString() || "N/A"}\n`;
  } else {
    md += `No salary data available across analyzed postings.\n`;
  }
  md += `\n`;

  // Remote Work Trends
  md += `## Remote Work Trends\n\n`;
  const rw = analysis.remoteWorkTrends;
  const rwTotal = rw.remote + rw.hybrid + rw.onsite + rw.notListed;
  if (rwTotal > 0) {
    md += `| Work Mode | Count | Percentage |\n`;
    md += `|-----------|-------|------------|\n`;
    md += `| Remote | ${rw.remote} | ${Math.round((rw.remote / rwTotal) * 100)}% |\n`;
    md += `| Hybrid | ${rw.hybrid} | ${Math.round((rw.hybrid / rwTotal) * 100)}% |\n`;
    md += `| Onsite | ${rw.onsite} | ${Math.round((rw.onsite / rwTotal) * 100)}% |\n`;
    md += `| Not Listed | ${rw.notListed} | ${Math.round((rw.notListed / rwTotal) * 100)}% |\n`;
  }
  md += `\n`;

  // Education Trends
  if (analysis.educationTrends.length > 0) {
    md += `## Education Requirements\n\n`;
    for (const edu of analysis.educationTrends) {
      md += `- ${edu}\n`;
    }
    md += `\n`;
  }

  // Common Responsibilities
  if (analysis.commonResponsibilities.length > 0) {
    md += `## Common Responsibilities\n\n`;
    for (const resp of analysis.commonResponsibilities) {
      md += `- ${resp}\n`;
    }
    md += `\n`;
  }

  // Industry Insights
  if (analysis.industryInsights.length > 0) {
    md += `## Industry Insights\n\n`;
    for (const insight of analysis.industryInsights) {
      md += `- ${insight}\n`;
    }
    md += `\n`;
  }

  md += `---\n\n`;
  md += `*Report generated by AI Job Search Assistant*\n`;

  saveFile(reportPath, md);
  logger.success(`Market report saved: ${reportPath}`);
}
