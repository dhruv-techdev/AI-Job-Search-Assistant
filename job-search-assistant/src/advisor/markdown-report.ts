import path from "path";
import { logger } from "../shared/logger.js";
import { saveFile, PATHS } from "../shared/tools.js";
import type { ApplicationReport } from "../shared/types.js";

/**
 * Generates a complete Markdown application report.
 */
export function generateApplicationMarkdownReport(
  report: ApplicationReport,
  outputName: string
): void {
  const filePath = path.join(PATHS.reports, `application-${outputName}.md`);

  let md = `# Application Report: ${report.jobTitle}\n\n`;
  md += `**Company:** ${report.companyName}\n`;
  md += `**Generated:** ${new Date(report.generatedAt).toLocaleString()}\n\n`;
  md += `---\n\n`;

  // Fit Assessment
  const fit = report.fitAssessment;
  const recLabels: Record<string, string> = {
    strong_fit: "Strong Fit ✅",
    good_fit: "Good Fit 👍",
    stretch: "Stretch 🔄",
    growth_target: "Growth Target 📈",
  };

  md += `## Fit Assessment\n\n`;
  md += `**Score:** ${fit.overallScore}/100\n`;
  md += `**Recommendation:** ${recLabels[fit.recommendation] || fit.recommendation}\n\n`;
  md += `${fit.recommendationText}\n\n`;

  // Skill Matches
  md += `### Skill Match Breakdown\n\n`;
  md += `| Skill | Status | Notes |\n`;
  md += `|-------|--------|-------|\n`;
  for (const s of fit.skillMatches) {
    const icon = s.status === "match" ? "✅" : s.status === "partial" ? "🔶" : "❌";
    md += `| ${s.skill} | ${icon} ${s.status} | ${s.note} |\n`;
  }
  md += `\n`;

  md += `**Experience:** ${fit.experienceMatch}\n\n`;
  md += `**Education:** ${fit.educationMatch}\n\n`;

  md += `---\n\n`;

  // Resume Adaptations
  if (report.resumeAdaptations.length > 0) {
    md += `## Resume Adaptation Suggestions\n\n`;
    for (let i = 0; i < report.resumeAdaptations.length; i++) {
      const s = report.resumeAdaptations[i];
      md += `### ${i + 1}. ${s.section}\n\n`;
      md += `**Current:** ${s.currentContent}\n\n`;
      md += `**Suggested:** ${s.suggestedChange}\n\n`;
      md += `**Why:** ${s.rationale}\n\n`;
    }
    md += `---\n\n`;
  }

  // Cover Letter Guidance
  const cl = report.coverLetterGuidance;
  if (cl.keyPoints.length > 0) {
    md += `## Cover Letter Strategy\n\n`;
    md += `### Key Points\n`;
    for (const p of cl.keyPoints) md += `- ${p}\n`;
    md += `\n### Strengths to Emphasize\n`;
    for (const s of cl.strengthsToEmphasize) md += `- ${s}\n`;
    if (cl.gapsToAddress.length > 0) {
      md += `\n### Gaps to Address\n`;
      for (const g of cl.gapsToAddress) md += `- ${g}\n`;
    }
    md += `\n### Company Angles\n`;
    for (const a of cl.companyAngles) md += `- ${a}\n`;
    md += `\n---\n\n`;
  }

  // Interview Preparation
  const ip = report.interviewPreparation;
  if (ip.likelyQuestions.length > 0) {
    md += `## Interview Preparation\n\n`;
    md += `### Likely Questions\n\n`;
    for (let i = 0; i < ip.likelyQuestions.length; i++) {
      const q = ip.likelyQuestions[i];
      md += `**${i + 1}. ${q.question}**\n\n`;
      md += `*Approach:* ${q.suggestedApproach}\n\n`;
    }

    md += `### Skills to Review\n`;
    for (const s of ip.skillsToReview) md += `- ${s}\n`;
    md += `\n### Company Research Points\n`;
    for (const p of ip.companyResearchPoints) md += `- ${p}\n`;
    md += `\n### Talking Points\n`;
    for (const t of ip.talkingPoints) md += `- ${t}\n`;
    md += `\n`;
  }

  md += `---\n\n`;
  md += `*Report generated by AI Job Search Assistant*\n`;

  saveFile(filePath, md);
  logger.success(`Markdown report saved: ${filePath}`);
}
